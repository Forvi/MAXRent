// money Форматирует сумму для текста договора.
func money(m listing.Money) string {
	return m.String()
}

// city Достаёт город из адреса объекта.
func city(d contract.Document) string {
	address := d.Listing.Address.String()
	if address == "" {
		return line
	}

	first, _, _ := strings.Cut(address, ",")

	return strings.TrimSpace(first)
}

// description Достаёт описание объекта из заявки.
func description(d contract.Document) string {
	if d.Listing.Description == "" {
		return line
	}

	return d.Listing.Description
}

// monthName Название месяца родительным падежом.
func monthName(t time.Time) string {
	months := [...]string{
		"января", "февраля", "марта", "апреля", "мая", "июня",
		"июля", "августа", "сентября", "октября", "ноября", "декабря",
	}

	return months[int(t.Month())-1]
}
